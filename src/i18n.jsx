export const LangContext = createContext('tr')

export function useT() {
  const lang = useContext(LangContext)
  const t = (key) => dict[lang]?.[key] ?? dict.tr[key] ?? key
  // Hazır tema adları gibi { tr, en } nesneleri için
  t.pick = (v) => (v && typeof v === 'object' ? v[lang] ?? v.tr : v)
  t.lang = lang
  return t
}
